import { expect, test } from '@playwright/test'
import { randomBytes } from 'node:crypto'

test('live backend: register, login, profile, session persistence and logout', async ({ page, context }) => {
  test.skip(process.env.APM_LIVE_TEST !== '1', 'Opt in with APM_LIVE_TEST=1; creates one isolated test account.')
  const username = `frontend_qa_${Date.now()}`, password = `Qa_${randomBytes(12).toString('hex')}`
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/chat')
  await expect(page).toHaveURL(/\/login/)
  await page.getByRole('link', { name: '创建账号', exact: true }).click()
  await page.getByLabel('账号', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByLabel('确认密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '创建账号并登录' }).click()
  await expect(page.getByRole('heading', { name: '聊天室', exact: true })).toBeVisible()
  expect((await context.cookies()).some(cookie => cookie.httpOnly && ['SESSION', 'JSESSIONID'].includes(cookie.name))).toBe(true)
  await page.getByRole('button', { name: '新建聊天室', exact: true }).click()
  await page.getByLabel('会话名称').fill('前端联调验证会话')
  await page.getByRole('button', { name: '创建聊天室', exact: true }).last().click()
  await expect(page.getByRole('heading', { name: '前端联调验证会话', exact: true })).toBeVisible()
  const roomUrl = page.url()
  // Verify all five new routes against the running backend, without uploading or charging model calls.
  const id = roomUrl.split('/').at(-1)!
  const current = (await (await page.request.get(`/api/chatSession/get?id=${id}`)).json()).data
  const library = await (await page.request.post('/api/paper/list/page', { data: { pageNum: 1, pageSize: 10, title: '', authors: '', topic: '', status: '' } })).json()
  expect(library.code).toBe(0); expect(library.data.records).toEqual([])
  const scope = await (await page.request.post('/api/sessionPaper/updateScope', { data: { sessionId: id, paperIds: [], scopeVersion: current.scopeVersion } })).json()
  expect(scope.code).toBe(0); expect(scope.data.paperIds).toEqual([]); expect(scope.data.scopeVersion).toBe(current.scopeVersion)
  const conflict = await (await page.request.post('/api/sessionPaper/updateScope', { data: { sessionId: id, paperIds: [], scopeVersion: current.scopeVersion + 1 } })).json()
  expect(conflict.code).toBe(40900)
  for (const endpoint of ['/paper/get?id=1', '/paperProcessingJob/get?id=1', '/paper/file?id=1']) {
    const response = await page.request.get(`/api${endpoint}`)
    expect((await response.json()).code).toBe(40400)
  }
  await page.getByRole('textbox', { name: '研究问题', exact: true }).fill('真实后端持久化草稿验证')
  await expect(page.getByText('草稿已同步', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('textbox', { name: '研究问题', exact: true })).toHaveValue('真实后端持久化草稿验证')
  await page.getByRole('button', { name: '重命名会话' }).click()
  await page.getByLabel('会话名称').fill('前端联调验证通过')
  await page.getByRole('button', { name: '保存名称' }).click()
  await expect(page.getByRole('heading', { name: '前端联调验证通过', exact: true })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出完整聊天记录' }).click()
  expect((await download).suggestedFilename()).toContain('前端联调验证通过')
  await page.goto('/profile')
  await page.getByLabel('昵称', { exact: true }).fill('前端验证研究员')
  await page.getByRole('button', { name: '保存资料' }).click()
  await expect(page.getByText('个人资料已保存。')).toBeVisible()
  await page.goto('/')
  await expect(page.locator('.metric-number').last()).toHaveText('1')
  await page.screenshot({ path: 'test-results/live-overview.png', fullPage: true })
  await page.goto(roomUrl)
  await page.getByRole('button', { name: '删除会话', exact: true }).click()
  await page.getByRole('button', { name: '确认删除' }).click()
  await expect(page).toHaveURL(/\/chat$/)
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('账号', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录工作空间' }).click()
  await expect(page.getByRole('heading', { name: '研究总览', exact: true })).toBeVisible()
  await expect(page.locator('.metric-number').last()).toHaveText('0')
  await page.getByRole('button', { name: '退出登录' }).click()
  expect(errors).toEqual([])
})
